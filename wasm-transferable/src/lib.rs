//! # wasm-transferable
//!
//! A framework that serializes Rust structs into [`JsValue`]
//! while simultaneously collecting any contained [`Transferable Objects`](https://developer.mozilla.org/docs/Web/API/Web_Workers_API/Transferable_objects).
//!
//! Enables seamless utilization of `Transferable Objects` when exchanging Rust structs via the `postMessage()` method of a `Worker` or `MessagePort`,
//! without the hassle of manual extraction.
//!
//! <div class="warning">
//! <p><strong>WARNING:</strong> This library is currently in a prototype stage.</p>
//! <p>
//! While all planned features have been implemented, unexpected bugs may occur, and backwards compatibility is not guaranteed.<br/>
//! Use in production environments is not recommended.
//! </p>
//! </div>
//!
//! # Transfer and Ownership Consumption
//!
//! Once an object is transferred, its contents are extracted, leaving it in an invalidated state.
//!
//! In JavaScript, attempting to use an invalidated object results in a runtime error.
//! This crate provides a framework that prevents such runtime errors by having [`Serialize::serialize`] consume ownership of the object.
//!
//! # Errors
//!
//! By leveraging generics, errors occurring during serialization and deserialization can be handled in a type-safe manner.
//!
//! When performing serialization, the design assumes that you define custom error types using crates such as [`thiserror`].
//!
//! When implementing [`Serialize`] or [`Deserialize`] with a custom error,
//! specifying a [`From`] trait bound like `From<MyError>` on the error type
//! makes it much easier to smoothly integrate error handling across types.

#![cfg_attr(docsrs, feature(doc_cfg))]

use std::vec;

use js_sys::{Array, ArrayIntoIter, Uint8Array};
use thiserror::Error;
use wasm_bindgen::{JsCast, JsValue};

mod extensions;

/// Provides an extension trait and its implementation
/// that enable posting a [`SerializeResult`] directly to types such as [`web_sys::MessagePort`] and [`web_sys::Worker`].
pub mod post_ext;

/// A derive macro that can implement [`Serialize`] and [`Deserialize`].
///
/// # Helper Attributes
/// #### Syntax Overview
/// ```ignore
/// #[transferable(
///     ser(
///         where_predicates(WherePredicates),
///         error_type_bounds(TypeParamBounds)
///     ),
///     des(
///         where_predicates(WherePredicates),
///         error_type_bounds(TypeParamBounds)
///     ),
///     where_predicates(WherePredicates)
///  )]
/// ```
///
/// #### `transferable` Helper Attribute
///
/// | Attribute | Type | Required / Optional | Description |
/// | :--- | :--- | :--- | :--- |
/// | `ser` | [SerializeOptions](#serializeoptions) | Optional | **Implements [`Serialize`].**<br>When specified, all field types must implement [`Serialize`]. |
/// | `des` | [DeserializeOptions](#deserializeoptions) | Optional | **Implements [`Deserialize`].**<br>When specified, all field types must implement [`Deserialize`]. |
/// | `where_predicates` | [WherePredicates](#wherepredicates) | Optional | Adds common trait bounds to all `impl` blocks generated by this macro. |
///
/// #### SerializeOptions
///
/// | Attribute | Type | Required / Optional | Description |
/// | :--- | :--- | :--- | :--- |
/// | `where_predicates` | [WherePredicates](#wherepredicates) | Optional | Adds trait bounds to the **type parameters of the type itself** in the [`Serialize`] implementation. |
/// | `error_type_bounds` | [TypeParamBounds](#typeparambounds) | Optional | Adds trait bounds to the **type parameter E** of [`Serialize<E>`]. |
///
/// #### DeserializeOptions
///
/// | Attribute | Type | Required / Optional | Description |
/// | :--- | :--- | :--- | :--- |
/// | `where_predicates` | [WherePredicates](#wherepredicates) | Optional | Adds trait bounds to the **type parameters of the type itself** in the [`Deserialize`] implementation. |
/// | `error_type_bounds` | [TypeParamBounds](#typeparambounds) | Optional | Adds trait bounds to the **type parameter E** of [`Deserialize<E>`]. |
///
/// #### WherePredicates
///
/// A list of trait bounds (to be placed inside a `where` clause).
///
/// Trailing commas are optional.
///
/// ```ignore
/// T: MyTrait1 + MyTrait2,
/// U: MyTrait3,
/// ```
///
/// #### TypeParamBounds
///
/// Trait bounds applied to type parameters (joined with +).
///
/// ```ignore
/// From<MyError> + MyTrait1 + MyTrait2
/// ```
///
/// # Examples
///
/// ```no_run
/// # use wasm_transferable::*;
/// #
/// # #[cfg(feature = "std-ext")]
/// #[derive(Transferable)]
/// #[transferable(ser)]
/// #[transferable(des(where_error(From<DeserializeError>)))]
/// struct GetFileOptions {
///     name: String,
///     create: bool
/// }
/// ```
///
/// ```no_run
/// # use wasm_transferable::*;
/// #
/// # #[cfg(feature = "std-ext")]
/// #[derive(Transferable)]
/// #[transferable(ser)]
/// #[transferable(des(where_error(From<DeserializeError>)))]
/// enum GetFileResult {
///     Success(Vec<u8>),
///     NotFound
/// }
/// ```
#[cfg(feature = "derive")]
pub use wasm_transferable_macro::Transferable;

/// The result of serialization.
pub struct SerializeResult {
    /// A JsValue containing serialized data.
    pub data: JsValue,
    /// An array of collected Transferable Objects.
    pub transfers: Array,
}

/// An error for deserializer initialization.
#[derive(Debug, Error)]
pub enum DeserializerInitializationError {
    /// When the structure of the source `JsValue` is invalid.
    #[error("invalid source JsValue structure")]
    Format,
}

/// A general-purpose error used in deserialization.
///
/// Represents a common error that occurs during the deserialization process,
/// primarily during the operation of the [`Deserializer`].
/// It is also used in custom deserialization logic for various types or as a general error type.
#[derive(Debug, Error)]
pub enum DeserializeError {
    /// When the structure of the source `JsValue` is invalid.
    #[error("invalid source JsValue structure")]
    Format,
}

/// A serializer that serializes a structure into a [`JsValue`] while simultaneously collecting `Transferable Objects`.
pub struct Serializer {
    binary: Vec<u8>,
    values: Array,
    transfers: Array,
}

impl Serializer {
    /// Creates a new serializer.
    #[allow(clippy::new_without_default)]
    pub fn new() -> Self {
        Self {
            binary: Vec::new(),
            values: Array::new(),
            transfers: Array::new(),
        }
    }

    /// Completes serialization and returns the result.
    pub fn end(self) -> SerializeResult {
        let Self {
            binary,
            values,
            transfers,
        } = self;

        // バイナリをUint8Arrayにして、valuesの先頭に追加
        let binary_buf = Uint8Array::new_from_slice(&binary);
        values.unshift(&binary_buf);
        transfers.push(&binary_buf.buffer());

        SerializeResult {
            data: values.into(),
            transfers,
        }
    }
}

impl Serializer {
    /// Adds Transferable Objects to the transfer list.
    ///
    /// > **Note:** This **only** adds them to the transfer list to mark them for transfer.
    /// >
    /// > **It must be used in conjunction with [`Serializer::js_value()`].**
    ///
    /// # Examples:
    /// ```
    /// # let mut ser = wasm_transferable::Serializer::new();
    /// # let typed_array = js_sys::Uint8Array::new_with_length(0);
    /// // typed_array: js_sys::Uint8Array
    /// ser.js_value(&typed_array);
    /// ser.transfer(&typed_array.buffer());
    /// ```
    pub fn transfer(&mut self, value: &JsValue) {
        self.transfers.push(value);
    }

    /// Serialize a [`JsValue`] value.
    pub fn js_value(&mut self, value: &JsValue) {
        self.values.push(value);
    }

    /// Serialize a value implementing [`Serialize`].
    pub fn transferable<T, E>(&mut self, value: T) -> Result<(), E>
    where
        T: Serialize<E>,
    {
        value.serialize(self)
    }

    /// Serialize a single byte value.
    pub fn byte(&mut self, byte: u8) {
        self.binary.push(byte);
    }

    /// Serialize fixed-length binary data.
    pub fn fixed_binary<const N: usize>(&mut self, bin: [u8; N]) {
        self.binary.extend(bin);
    }
}

/// A deserializer that restores a structure from a [`JsValue`] serialized by [`Serializer`].
pub struct Deserializer {
    binary: vec::IntoIter<u8>,
    values: ArrayIntoIter<JsValue>,
}

impl Deserializer {
    /// Creates a new deserializer from a [`JsValue`] serialized by [`Serializer`].
    pub fn new(data: JsValue) -> Result<Self, DeserializerInitializationError> {
        let message: Array = data
            .dyn_into()
            .map_err(|_| DeserializerInitializationError::Format)?;

        let mut values = message.into_iter();

        // 先頭にある、シリアライズされたvaluesのUInt8Arrayを引き出す
        let binary_buf = values
            .next()
            .ok_or(DeserializerInitializationError::Format)?;
        let binary_buf: Uint8Array = binary_buf
            .dyn_into()
            .map_err(|_| DeserializerInitializationError::Format)?;

        let binary = binary_buf.to_vec().into_iter();

        Ok(Self { binary, values })
    }
}

impl Deserializer {
    /// Deserialize a [`JsValue`] value.
    pub fn js_value(&mut self) -> Result<JsValue, DeserializeError> {
        self.values.next().ok_or(DeserializeError::Format)
    }

    /// Deserialize a value implementing [`Deserialize`].
    pub fn transferable<T, E>(&mut self) -> Result<T, E>
    where
        T: Deserialize<E>,
    {
        T::deserialize(self)
    }

    /// Deserializes a single byte value.
    pub fn byte(&mut self) -> Result<u8, DeserializeError> {
        self.binary.next().ok_or(DeserializeError::Format)
    }

    /// Deserializes fixed-length binary data.
    pub fn fixed_binary<const N: usize>(&mut self) -> Result<[u8; N], DeserializeError> {
        array_init::from_iter(self.binary.by_ref()).ok_or(DeserializeError::Format)
    }
}

/// Serialize to [`JsValue`] while collecting Transferable Objects.
///
/// > note: Using the [`derive@wasm_transferable_macro::Transferable`] derive macro is convenient and safe.
pub trait Serialize<E> {
    /// Consumes `self` to perform serialization.
    ///
    /// > 注意: The serialization order must match [`Deserialize::deserialize`].
    fn serialize(self, ser: &mut Serializer) -> Result<(), E>;
}

/// Deserialize a type from a [`JsValue`].
///
/// > note: Using the [`derive@wasm_transferable_macro::Transferable`] derive macro is convenient and safe.
pub trait Deserialize<E>
where
    Self: Sized,
{
    /// デシリアライズして自身を復元します。
    ///
    /// > The deserialization order must match [`Serialize::serialize`].
    fn deserialize(des: &mut Deserializer) -> Result<Self, E>;
}

/// Serialize any value implementing [`Serialize`].
pub fn serialize<T, E>(value: T) -> Result<SerializeResult, E>
where
    T: Serialize<E>,
{
    let mut ser = Serializer::new();
    ser.transferable(value)?;
    Ok(ser.end())
}

/// Deserializes a [`JsValue`] into any type implementing [`Deserialize`].
///
/// > **Note:** If the `data` argument is not an intended value[^1], **deserialization may succeed without error, yielding unexpected results**.
///
/// [^1]: An *intended value* refers to a [`SerializeResult::data`] produced by the [`serialize`] function with a matching type argument `T`.
pub fn deserialize<T, E>(data: JsValue) -> Result<T, E>
where
    T: Deserialize<E>,
    E: From<DeserializerInitializationError>,
{
    let mut des = Deserializer::new(data)?;
    let value = des.transferable::<T, E>()?;
    Ok(value)
}
